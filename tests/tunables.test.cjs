// ---------- in a browser ----------

async function inBrowser(url, run) {
  const puppeteer = require(BROWSER.puppeteerModule);
  const browser = await puppeteer.launch({ executablePath: BROWSER.chrome, headless: true, args: ["--allow-file-access-from-files"] });
  try {
    const page = await browser.newPage();
    await page.setViewport({ width: 640, height: 360 });
    await page.evaluateOnNewDocument(() => { window.__timelines = window.__timelines || {}; });
    await page.goto(url, { waitUntil: "load" });
    return await run(page);
  } finally { await browser.close(); }
}
const fileUrl = (dir) => `file:///${path.join(dir, "index.html").replaceAll("\\", "/")}`;

