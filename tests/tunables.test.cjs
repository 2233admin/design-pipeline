test("check reports each failure with a fix and exits 2", () => {
  const dir = makePage(tmp());
  const file = (name) => path.join(dir, name);
  const edit = (change) => { const doc = JSON.parse(fs.readFileSync(file("tunables.json"), "utf8")); change(doc); fs.writeFileSync(file("tunables.json"), `${JSON.stringify(doc, null, 2)}\n`); };
  try {
    const clean = tn(dir, "check");
    assert.equal(clean.status, 0, JSON.stringify(clean.body));
    assert.deepEqual(clean.body.findings, []);
    assert.equal(clean.body.reads.accent[0], "index.html");

    edit((doc) => { doc.params.push({ ...doc.params[0] }); });
    let result = tn(dir, "check");
    assert.equal(result.status, 2);
    assert.deepEqual(codes(result.body), ["tunables-invalid"]);
    assert.equal(result.body.findings[0].id, "accent");
    edit((doc) => { doc.params.pop(); });

    edit((doc) => { doc.values.accent = "red"; });
    result = tn(dir, "check");
    assert.deepEqual(codes(result.body), ["value-invalid"]);
    assert.equal(result.body.findings[0].id, "accent");
    edit((doc) => { delete doc.values.accent; doc.values.ghost = 1; });
    assert.deepEqual(codes(tn(dir, "check").body), ["value-unknown"]);
    edit((doc) => { delete doc.values.ghost; });
    assert.equal(tn(dir, "check").status, 0);

    edit((doc) => { doc.values.density = "compact"; });
    result = tn(dir, "check");
    assert.deepEqual(codes(result.body), ["script-stale"], "tunables.json changed by hand and sync has not run");
    assert.match(result.body.findings[0].fix, /tunables sync/);
    assert.equal(tn(dir, "sync").status, 0);
    assert.equal(tn(dir, "check").status, 0);

    edit((doc) => { doc.params.push({ id: "unused", label: "Unused", group: "copy", type: "text", default: "x" }); });
    tn(dir, "sync");
    result = tn(dir, "check");
    assert.deepEqual(codes(result.body), ["param-unread"]);
    assert.equal(result.body.findings[0].id, "unused");
    edit((doc) => { doc.params.at(-1).dynamic = true; });
    tn(dir, "sync");
    assert.equal(tn(dir, "check").status, 0, "a dynamic param is not reported as unread");

    const html = fs.readFileSync(file("index.html"), "utf8");
    fs.writeFileSync(file("index.html"), html.replace("</body>", '<script>tunable("nope");</script></body>'));
    result = tn(dir, "check");
    assert.deepEqual(codes(result.body), ["read-undeclared"]);
    assert.equal(result.body.findings[0].id, "nope");
    fs.writeFileSync(file("index.html"), html);

    fs.writeFileSync(file("index.html"), html.replace('<script src="tunables.js"></script>', ""));
    assert.deepEqual(codes(tn(dir, "check").body), ["script-not-included"]);
    fs.writeFileSync(file("index.html"), html.replace('<script src="tunables.js"></script>', "<script>var early = 1;</script><script src=\"tunables.js\"></script>"));
    assert.deepEqual(codes(tn(dir, "check").body), ["script-not-included"], "an inline script runs before it");
    fs.writeFileSync(file("index.html"), html.replace('<script src="tunables.js"></script>', '<script src="https://cdn.example/lib.js"></script><script src="tunables.js"></script>'));
    assert.equal(tn(dir, "check").status, 0, "a library from a CDN may come first");
    fs.writeFileSync(file("index.html"), html);
  } finally { cleanup(dir); }
});

