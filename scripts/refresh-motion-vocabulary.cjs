#!/usr/bin/env node
"use strict";

// Maintenance code for skill/references/motion-vocabulary.json; nothing under skill/ runs it.
//
//   node scripts/refresh-motion-vocabulary.cjs --checkout <clone of emilkowalski/skills>
//     Rewrites tests/fixtures/motion-vocabulary/upstream-terms.json: the glossary of
//     skills/animation-vocabulary/SKILL.md read at the revision sources.lock.json records for
//     `emilkowalski-animation-review`. tests/motion-vocabulary.test.cjs holds the vocabulary against
//     it, so a term upstream added, reworded or removed fails there until the vocabulary follows.
//   node scripts/refresh-motion-vocabulary.cjs --catalog
//     Rewrites the `motion-vocabulary/*` doc records of skill/references/component-source-catalog.json
//     from the vocabulary. The records are generated; edit the vocabulary, never the records.
//   node scripts/refresh-motion-vocabulary.cjs --check
//     Exits 1 when those records differ from what the vocabulary generates.

const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { git, readLock } = require("./sources-lock.cjs");

const repoRoot = path.resolve(__dirname, "..");
const LOCK_ID = "emilkowalski-animation-review";
const UPSTREAM_PATH = "skills/animation-vocabulary/SKILL.md";
const VOCABULARY = "skill/references/motion-vocabulary.json";
const CATALOG = "skill/references/component-source-catalog.json";
const GUIDE = "references/motion-vocabulary.md";
const FIXTURE = "tests/fixtures/motion-vocabulary/upstream-terms.json";
const FIXTURE_SCHEMA = "design-pipeline.motion-vocabulary-fixture.v1";
const RECORD_PREFIX = "motion-vocabulary/";
const CATEGORY = "motion-vocabulary";
const OWNED_SOURCE_ID = "design-pipeline/motion-vocabulary";

function fail(message) {
  throw new Error(message);
}

// "Squash & stretch" -> "squash-and-stretch", "3D tilt / Flip" -> "3d-tilt-flip".
function slug(text) {
  return text.toLowerCase().replace(/&/g, " and ").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
}

// The `## Glossary` section: `### <Category> — <what it covers>` headings, each followed by
// `- **<Term>** — <definition>` lines. Anything else in that section is a format this parser does
// not know and fails, so a reshaped upstream file cannot silently drop terms.
function parseGlossary(text) {
  const lines = text.split(/\r?\n/);
  const start = lines.indexOf("## Glossary");
  if (start < 0) fail(`${UPSTREAM_PATH} has no "## Glossary" heading`);
  const categories = [];
  const terms = [];
  let category = null;
  for (let index = start + 1; index < lines.length; index += 1) {
    const line = lines[index];
    if (/^## /.test(line)) break;
    if (!line.trim() || /^_.*_$/.test(line.trim())) continue;
    const heading = line.match(/^### (.+?) — (.+)$/);
    if (heading) {
      category = { id: slug(heading[1]), name: heading[1], description: heading[2] };
      categories.push(category);
      continue;
    }
    const term = line.match(/^- \*\*(.+?)\*\* — (.+)$/);
    if (!term || !category) fail(`${UPSTREAM_PATH}:${index + 1} is not a category heading or a term line: ${line.slice(0, 80)}`);
    terms.push({ id: slug(term[1]), term: term[1], category: category.id, definition: term[2] });
  }
  if (!terms.length) fail(`${UPSTREAM_PATH} has no glossary terms`);
  const ids = terms.map((item) => item.id);
  const repeated = ids.filter((id, index) => ids.indexOf(id) !== index);
  if (repeated.length) fail(`${UPSTREAM_PATH} repeats term ids: ${repeated.join(", ")}`);
  return { categories, terms };
}

function refreshFixture(root, checkout) {
  const locked = readLock(root).sources.find((entry) => entry.id === LOCK_ID);
  if (!locked) fail(`sources.lock.json has no ${LOCK_ID}`);
  const bytes = git(checkout, ["cat-file", "blob", `${locked.revision}:${UPSTREAM_PATH}`], { buffer: true, allowFailure: true });
  if (bytes === null) fail(`${checkout} has no ${UPSTREAM_PATH} at the locked revision ${locked.revision.slice(0, 12)}; fetch it first`);
  const { categories, terms } = parseGlossary(bytes.toString("utf8"));
  const fixture = {
    schema: FIXTURE_SCHEMA,
    note: "Generated by scripts/refresh-motion-vocabulary.cjs --checkout from the upstream file at the named revision; the definitions are quoted from it under its MIT license (THIRD_PARTY_NOTICES.md). Do not edit by hand.",
    source: { id: LOCK_ID, repo: locked.repo, revision: locked.revision, path: UPSTREAM_PATH, sha256: crypto.createHash("sha256").update(bytes).digest("hex") },
    categories,
    terms,
  };
  const file = path.join(root, FIXTURE);
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(fixture, null, 2)}\n`);
  return { fixture: FIXTURE, revision: locked.revision, sha256: fixture.source.sha256, categories: categories.length, terms: terms.length };
}

// The canonical source record the project-owned anti-pattern records point at.
const OWNED_SOURCE = Object.freeze({
  id: `source/${OWNED_SOURCE_ID}`,
  sourceId: OWNED_SOURCE_ID,
  recordType: "source",
  name: "Project-owned motion vocabulary additions / 动效词表自有条目",
  availability: "project-owned",
  localPaths: { guide: GUIDE, catalog: path.posix.relative("skill", VOCABULARY) },
  provenance: {
    source: "design-pipeline motion vocabulary",
    license: "project-owned",
    attribution: "Canonical ownership record for the named anti-patterns, aliases, close-term notes and local links; quoted terms and definitions belong to their upstream source record.",
  },
  license: { state: "project-owned", evidence: [GUIDE, path.posix.relative("skill", VOCABULARY)] },
  boundary: "project-owned",
  webRanking: false,
  description: "Named motion anti-patterns with the term to use instead, plus the colloquial aliases, close-term notes and packaged-resource links added to the quoted upstream glossary.",
});

function flatAliases(aliases) {
  return [...aliases.en, ...aliases.zh];
}

// One catalog doc record per term and per anti-pattern. `description` is the definition, so a search
// result is the answer; `motionVocabulary` carries the close terms, named anti-patterns and the
// packaged resources the term links to.
function catalogRecords(vocabulary) {
  const termById = new Map(vocabulary.terms.map((term) => [term.id, term]));
  const categoryById = new Map(vocabulary.categories.map((category) => [category.id, category]));
  const upstream = vocabulary.source;
  const license = `${upstream.repository}/blob/${upstream.revision}/LICENSE`;
  const termRecords = vocabulary.terms.map((term) => ({
    id: `${RECORD_PREFIX}${term.id}`,
    sourceId: "emilkowalski/skills",
    recordType: "term",
    name: term.term,
    category: CATEGORY,
    description: term.definition,
    aliases: flatAliases(term.aliases),
    keywords: [term.id, term.category, categoryById.get(term.category).name],
    availability: "bundled-implementation",
    localPaths: { guide: GUIDE, catalog: path.posix.relative("skill", VOCABULARY) },
    motionVocabulary: {
      kind: "term",
      termId: term.id,
      group: term.category,
      closeTerms: term.closeTerms.map((close) => ({ id: close.id, term: termById.get(close.id).term, difference: close.difference })),
      antiPatterns: vocabulary.antiPatterns.filter((item) => item.terms.includes(term.id)).map((item) => ({ id: item.id, name: item.name })),
      local: term.local,
    },
    provenance: {
      source: "emilkowalski/skills animation-vocabulary glossary",
      license: upstream.license,
      url: upstream.repository,
      revision: upstream.revision,
      attribution: `Term and definition quoted verbatim from ${upstream.path}; aliases, close-term notes and local links are this repository's.`,
    },
    license: { state: "verified", id: upstream.license, evidence: [license] },
    licenseScope: `Explicit ${upstream.license} grant at revision ${upstream.revision}; covers the quoted term and definition. Aliases, close-term notes and local links are project-owned.`,
    webRanking: false,
  }));
  const antiPatternRecords = vocabulary.antiPatterns.map((item) => ({
    id: `${RECORD_PREFIX}${item.id}`,
    sourceId: OWNED_SOURCE_ID,
    recordType: "term",
    name: item.name,
    category: CATEGORY,
    description: item.description,
    aliases: flatAliases(item.aliases),
    keywords: [item.id, "anti-pattern"],
    availability: "project-owned",
    localPaths: { guide: GUIDE, catalog: path.posix.relative("skill", VOCABULARY) },
    motionVocabulary: {
      kind: "anti-pattern",
      antiPatternId: item.id,
      replacement: { id: item.replacement, term: termById.get(item.replacement).term },
      fix: item.fix,
      terms: item.terms.map((id) => ({ id, term: termById.get(id).term })),
      sources: item.sources,
    },
    provenance: {
      source: "design-pipeline motion vocabulary",
      license: "project-owned",
      attribution: item.origin,
    },
    license: { state: "project-owned", evidence: [path.posix.relative("skill", VOCABULARY)] },
    licenseScope: "Project-owned name, description and fix; the rules it cites keep their own licenses.",
    webRanking: false,
  }));
  return [...termRecords, ...antiPatternRecords, OWNED_SOURCE];
}

function isVocabularyRecord(record) {
  return record.id.startsWith(RECORD_PREFIX) || record.id === OWNED_SOURCE.id;
}

function readJson(root, file) {
  return JSON.parse(fs.readFileSync(path.join(root, file), "utf8"));
}

function catalogWithRecords(root) {
  const catalog = readJson(root, CATALOG);
  const kept = catalog.docs.filter((record) => !isVocabularyRecord(record));
  return { ...catalog, docs: [...kept, ...catalogRecords(readJson(root, VOCABULARY))] };
}

function writeCatalog(root) {
  const next = catalogWithRecords(root);
  fs.writeFileSync(path.join(root, CATALOG), `${JSON.stringify(next, null, 2)}\n`);
  return { catalog: CATALOG, records: next.docs.filter(isVocabularyRecord).length };
}

function catalogIsCurrent(root) {
  return `${JSON.stringify(catalogWithRecords(root), null, 2)}\n` === fs.readFileSync(path.join(root, CATALOG), "utf8");
}

if (require.main === module) {
  try {
    const [mode, value, ...rest] = process.argv.slice(2);
    if (rest.length || !["--checkout", "--catalog", "--check"].includes(mode) || (mode === "--checkout") !== Boolean(value)) {
      fail("usage: refresh-motion-vocabulary.cjs --checkout <clone of emilkowalski/skills> | --catalog | --check");
    }
    if (mode === "--check") {
      if (!catalogIsCurrent(repoRoot)) fail(`${CATALOG} differs from ${VOCABULARY}; run node scripts/refresh-motion-vocabulary.cjs --catalog`);
      process.stdout.write("OK motion vocabulary catalog records are current\n");
    } else {
      process.stdout.write(`${JSON.stringify(mode === "--checkout" ? refreshFixture(repoRoot, path.resolve(value)) : writeCatalog(repoRoot), null, 2)}\n`);
    }
  } catch (error) {
    process.stderr.write(`FAIL ${error.message}\n`);
    process.exit(1);
  }
}

module.exports = { CATALOG, CATEGORY, FIXTURE, FIXTURE_SCHEMA, GUIDE, LOCK_ID, RECORD_PREFIX, UPSTREAM_PATH, VOCABULARY, catalogIsCurrent, catalogRecords, parseGlossary, refreshFixture, slug, writeCatalog };
